"""Generate fw/ui/h7_font.c: an 8 x 16 bitmap font for ASCII 32..126 from DejaVu Sans Mono, rasterised without anti-aliasing.

    python3 tools/gen_font.py [path/to/DejaVuSansMono.ttf]

The glyph bitmaps are derived from DejaVu Sans Mono (Bitstream Vera licence: free to use and embed, the font itself is not
redistributed here). One byte per row, bit 7 the left pixel. Needs Pillow."""
import os, sys
from PIL import Image, ImageDraw, ImageFont

TTF = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
W, H, FIRST, LAST = 8, 16, 32, 126
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "fw", "ui", "h7_font.c")


def glyph(font, ch):
    im = Image.new("1", (W, H), 0)
    ImageDraw.Draw(im).text((0, -2), ch, font=font, fill=1)
    px = im.load()
    return [sum((1 << (7 - x)) for x in range(W) if px[x, y]) for y in range(H)]


def main():
    font = ImageFont.truetype(TTF, 13)
    asc, desc = font.getmetrics()
    rows = ["/* Generated by tools/gen_font.py from DejaVu Sans Mono; do not edit. 8 x 16, ASCII 32..126, one byte per row, bit 7 = left pixel. */",
            "#include \"h7_font.h\"", "", "const uint8_t h7_font8x16[95][16] = {"]
    for c in range(FIRST, LAST + 1):
        g = glyph(font, chr(c))
        rows.append("\t{ " + ", ".join("0x%02X" % b for b in g) + " },\t/* %s */" % (chr(c) if chr(c) not in "\\*/" else "0x%02X" % c))
    rows.append("};")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f: f.write("\n".join(rows) + "\n")
    print("wrote", os.path.normpath(OUT), "ascent", asc, "descent", desc)


if __name__ == "__main__":
    main()
