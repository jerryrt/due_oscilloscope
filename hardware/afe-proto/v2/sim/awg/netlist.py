"""Netlist builder and ngspice runner for the v2 AWG (shared by run.py).  numpy only.

Every deck runs through simtools.netlib_common.run_ng: under the memory cap, with a .save of exactly the vectors its
.control block reads (the `noise` deck is left unrestricted: ngspice aborts a noise analysis under a .save). The op-amp
macro comes from simtools.vendor, never from a path written down here. `workdir()` says where netlists, wrdata files
and logs go (a temporary directory unless set), so nothing is written beside the code.
"""
import os, re, hashlib, tempfile
import numpy as np
from simtools import netlib_common as _C
from simtools import vendor
from params import RAILS, D, KT4                      # noqa: F401  (re-exported: run.py reads nl.RAILS, nl.D)

HERE = os.path.dirname(os.path.abspath(__file__))
VENDOR_SHA = vendor.TPH2501_DERIVED_SHA
MEM = os.environ.get('DUE_NG_MEM', '2G')
_WORK = [None]


def set_workdir(path):
    """Where netlists/ and raw/ live for this process (created on first use)."""
    _WORK[0] = os.path.abspath(path)
    os.makedirs(netdir(), exist_ok=True); os.makedirs(rawdir(), exist_ok=True)


def workdir():
    if _WORK[0] is None:
        set_workdir(tempfile.mkdtemp(prefix='v2-awg-'))
    return _WORK[0]


def netdir():
    return os.path.join(workdir(), 'netlists')


def rawdir():
    return os.path.join(workdir(), 'raw')


def vendor_path():
    return str(vendor.tph2501_ngspice())


def model_text(model='vendor'):
    """The op-amp include text.  model: 'vendor' (3PEAK's TPH2501 macro, with the derived saturation), or 'BEH21' / 'BEH60', the
    project's datasheet-fitted small-signal models (models-open/tph2502-beh, open-loop output resistance 21 / 60 ohm): small signal
    only, no rails, no saturation, so used for the stability rows (AN-1).  The vendor text still carries @VENDOR@; model_include fills it."""
    if model in ('BEH21', 'BEH60'):
        ro = model[3:]
        return (f".include {vendor.tph2502_beh()}\n.subckt TPH2502 inp inn vp vn out\nXb inp inn vp vn out TPH2502_BEH ro={ro}\n.ends TPH2502\n"
                f".subckt TPH2502_SAT inp inn vp vn out params: rsat=11.5\nXb inp inn vp vn out TPH2502_BEH ro={ro}\n.ends TPH2502_SAT\n")
    with open(os.path.join(HERE, 'models/tph2502.inc')) as f:
        return f.read()


def model_include(model='vendor', macro=None):
    """model_text with the vendor macro's path filled in (an absolute path, or `macro` when a document wants a name)."""
    t = model_text(model)
    return t.replace('@VENDOR@', macro or vendor_path()) if '@VENDOR@' in t else t


def _ladder(node, end):
    n = 10; L = []
    prev = node
    for i in range(n):
        L.append(f"Lc{i} {prev} lc{i} 25n\nCc{i} lc{i} 0 10p"); prev = f'lc{i}'
    L.append(f"Rl {prev} 0 1G" if end == 'open' else f"Rl {prev} 0 50")
    return "\n".join(L)


def load_lines(load, node='bnc'):
    return {
        'hiz': f"Rl {node} 0 1Meg\nCl {node} 0 15p",
        'open': f"Rl {node} 0 1G",
        'r50': f"Rl {node} 0 50",
        'short': f"Rl {node} 0 1m",
        'cap100': f"Rl {node} 0 1G\nCl {node} 0 100p",
        'cap330': f"Rl {node} 0 1G\nCl {node} 0 330p",
        'cap1n': f"Rl {node} 0 1G\nCl {node} 0 1n",
        'cable_open': f"T1 {node} 0 far 0 Z0=50 TD=5n\nRl far 0 1G",
        'cable_r50': f"T1 {node} 0 far 0 Z0=50 TD=5n\nRl far 0 50",
        # the same 5 ns, 50 ohm line as ten LC sections (L 25 nH, C 10 pF each): the lossless T element makes the transient stall
        # at 28 ps against the op-amp macro's diodes once the stage has its feedback capacitor
        'ladder_open': _ladder(node, 'open'),
        'cable_scope': f"T1 {node} 0 far 0 Z0=50 TD=5n\nRl far 0 1Meg\nCl far 0 15p",
    }[load]


def build(p=None, analysis='.op', ac=(), dcsrc=None, extra='', fbbreak=False, supply='dc', quiet=True):
    """The AWG netlist.  ac: names of sources given AC 1: 'dac', 'vp', 'vn'.  fbbreak: break the loop of half B at its
    inverting input (large L keeps DC; AC injected through a large C).  supply 'dc' | 'off' (rails 0 V) | 'pwl:...' (extra)."""
    q = dict(D); q.update(p or {})
    vp_, vn_ = RAILS[q['rails']] if isinstance(q['rails'], str) else q['rails']
    L = [f"* v2 AWG output stage, TPH2502 dual: both halves paralleled as one gain stage (V2-2: no spare half); generated by core.build",
         model_include(q['model'], macro=q.get('macro_name'))]
    acs = lambda n: ' AC 1' if n in ac else ''
    dcv = q['dac'] if dcsrc is None else dcsrc
    if supply == 'off':
        L.append(f"Vvp vpx 0 DC 0{acs('vp')}\nVvn vnx 0 DC 0{acs('vn')}")
    elif supply.startswith('src:'):
        L.append(supply[4:])
    else:
        L.append(f"Vvp vpx 0 DC {vp_}{acs('vp')}\nVvn vnx 0 DC {vn_}{acs('vn')}")
    L.append(f"Rvp vpx vcc {q['rp']}\nRvn vnx vee {q['rn']}")
    L.append(f"Cdp vcc 0 {q['Cdec']}\nCdn vee 0 {q['Cdec']}")
    if q.get('dacsrc') is None:
        L.append(f"Vdac dacs 0 DC {dcv}{acs('dac')}\nRdacs dacs dac 1m")
    else:
        L.append(q['dacsrc'])
    L.append(f"Rbin dac bin {q['Rbin']}\nRbpl bin 0 {q['Rbpl']}")
    topo = q.get('topo', 'Par')
    M = 'TPH2502_SAT' if q.get('sat') else 'TPH2502'
    pin = 'fbp' if fbbreak else 'fb'
    if topo == 'Par':        # both halves are one gain stage: + inputs on the DAC node, - inputs on fb, outputs via Rb to vo
        L.append(f"XA bin {pin} vcc vee oa {M}\nXB bin {pin} vcc vee ob {M}")
        L.append(f"Rba oa vo {q['Rb']}\nRbb ob vo {q['Rb']}")
        gain_out = 'vo'
    elif topo == 'Single':   # one half only; the other is tied off as a follower of ground
        L.append(f"XA bin {pin} vcc vee oa {M}\nXB 0 xbn vcc vee xbn {M}")
        L.append(f"Rba oa vo {q['Rb']}")
        gain_out = 'vo'
    elif topo == 'Again':    # A has the gain and the offset network, B is a unity follower driving the 50 ohm
        L.append(f"XA bin {pin} vcc vee ao TPH2502")
        L.append(f"Rs ao bp {max(q['Rs'], 1e-3)}\nCs bp 0 {max(q['Cs'], 1e-18)}\nCpv bp 0 {q['cpv']}")
        L.append("XB bp vo vcc vee vo TPH2502")
        gain_out = 'ao'
    L.append(f"Rf {gain_out} fb {q['Rf']}\nRg2 fb vref {q['Rg2']}\nCfb fb 0 {q["cfb"]}")
    if np.isfinite(q['Rg1']):            # the design omits Rg1 (design.md): K = Rf/Rg2 = Gs - 1 is not needed to be smaller
        L.append(f"Rg1 fb 0 {q['Rg1']}")
    if q.get('refsrc') is not None:         # a raw source for the offset reference (start-up cases)
        L.append(q['refsrc'])
    elif q['vref'] is not None:             # the REF3030E (D-V2-12): 3.000 V behind 0.05 ohm with its own 1 uF + 100 nF; no filter, Rvr 0
        L.append(f"Vrf vrfs 0 DC {q['vref']}\nRzr vrfs vrf0 {q['zref']}\nCzr vrf0 0 {q['Cref']}")
        L.append(f"Rvr vrf0 vref {max(q['Rvr'], 1e-6)}\nCvr vref 0 {q['Cvr']}")      # the offset filter (D-V2-12 follow-up): Rvr then Cvr to ground, Rg2 from the Cvr node
    else:                                   # the +3.3 V rail through Rvr and Cvr (the superseded arrangement)
        L.append(f"Rvr vpx vref {q['Rvr']}\nCvr vref 0 {q['Cvr']}")
    if q['Cf'] > 0:
        L.append(f"Cf {gain_out} fb {q['Cf']}")
    if topo == 'Par':
        L.append(f"Cpv bin 0 {q['cpv']}")
        if q['cpx'] > 0:
            L.append(f"Cpx bin 0 {q['cpx']}")      # +IN to ground, after Rbin: the stability capacitor (AN-1, design.md)
    if fbbreak:
        L.append("Lbk fb fbp 1G\nCbk vsb fbp 1000\nVsb vsb 0 DC 0 AC 1")
    L.append(f"Ro vo bnc {q['Rout']}")
    if q.get('Cout', 0) > 0:
        L.append(f"Cout bnc 0 {q['Cout']}")
    L.append(load_lines(q['load']))
    L.append(extra)
    L.append(analysis)
    L.append(".end")
    return "\n".join(L) + "\n"


def run(name, text, vecs, timeout=200):
    """Write netlists/<name>.cir, run ngspice -b under the cap with a .save of the vectors its .control block reads, and
    return (path of its wrdata file, ngspice's log)."""
    out = os.path.join(rawdir(), name + '.dat')
    if '.control' not in text:
        raise ValueError('netlist must carry a .control block')
    text = text.replace('@OUT@', out)
    if os.path.exists(out): os.remove(out)          # a stale result from an earlier run must never be read back
    log = _C.run_ng(netdir(), os.path.join(workdir(), 'work'), '', name, text, timeout, mem=MEM)
    with open(os.path.join(rawdir(), name + '.log'), 'w') as f:
        f.write(log)
    if 'aborted' in log:
        raise RuntimeError(f'{name}: ngspice aborted the analysis\n' + log[-600:])
    if not os.path.exists(out) or os.path.getsize(out) == 0:
        raise RuntimeError(f'{name}: no output\n' + log[-1500:])
    return out, log


def wr(name, base, analysis, vecs, setup='', post=''):
    """Common wrapper: base netlist text (no .control yet), an analysis command and a vector list -> dict."""
    ctl = f".control\nset wr_vecnames\nset wr_singlescale\n{setup}\n{analysis}\n{post}\nwrdata @OUT@ {' '.join(vecs)}\n.endc\n"
    text = base.replace('.end\n', '') + ctl + ".end\n"
    out, log = run(name, text, vecs)
    with open(out) as f:
        head = f.readline().split()
    data = np.loadtxt(out, skiprows=1)
    if data.ndim == 1: data = data[None, :]
    return head, data, log


def noise(name, p=None, f1=10.0, f2=1e9, ppd=20, load='hiz', extra=''):
    """Output noise density at the BNC with DAC0 a quiet DC source (rout 1 mohm).  Returns f, onoise (V/rtHz) and the
    breakdown by device is left to ngspice's own `.noise` 'print' (not used)."""
    b = build(dict(p or {}, load=load), analysis='', extra=extra, ac=('dac',))
    ctl = f".control\nset wr_vecnames\nset wr_singlescale\nnoise v(bnc) Vdac dec {ppd} {f1} {f2} 1\nsetplot noise1\nwrdata @OUT@ onoise_spectrum\n.endc\n"
    text = b.replace('.end\n', '') + ctl + ".end\n"
    out, log = run(name, text, None)
    d = np.loadtxt(out, skiprows=1)
    return d[:, 0], d[:, 1]


def integ(f, y2, lo=None, hi=None):
    """sqrt of the integral of y2 (V^2/Hz) over f (trapezoid in linear f), optionally limited."""
    m = np.ones_like(f, bool)
    if lo is not None: m &= f >= lo
    if hi is not None: m &= f <= hi
    ff, yy = f[m], y2[m]
    return float(np.sqrt(np.sum(0.5 * (yy[1:] + yy[:-1]) * np.diff(ff))))


def phase_margin(p, load, fmin=1e3, fmax=2e9, tag='pm'):
    """Loop break at the inverting input pins of the gain stage (large L keeps DC, AC injected through a large C):
    T = -v(fb)/v(fbp).  Returns (crossover MHz, phase margin deg, gain margin dB or nan, DC loop gain)."""
    b = build(dict(p, load=load), analysis='', fbbreak=True)
    h, d, log = wr(f'{tag}', b, f'ac dec 80 {fmin} {fmax}', ['v(fb)', 'v(fbp)'])
    f = d[:, 0]; T = -(d[:, 1] + 1j * d[:, 2]) / (d[:, 3] + 1j * d[:, 4])
    mag = np.abs(T)
    ph = np.degrees(np.unwrap(np.angle(T)))
    ph = ph - 360 * np.round((ph[0]) / 360)         # DC phase 0
    i = np.where(mag < 1)[0][0]
    w = (0 - np.log(mag[i - 1])) / (np.log(mag[i]) - np.log(mag[i - 1]))
    fc = np.exp(np.log(f[i - 1]) + w * (np.log(f[i]) - np.log(f[i - 1])))
    phc = ph[i - 1] + w * (ph[i] - ph[i - 1])
    gm = float('nan')
    j = np.where(ph < -180)[0]
    if len(j):
        j = j[0]; wj = (-180 - ph[j - 1]) / (ph[j] - ph[j - 1])
        gm = -20 * np.log10(np.exp(np.log(mag[j - 1]) + wj * (np.log(mag[j]) - np.log(mag[j - 1]))))
    return fc / 1e6, 180 + phc, gm, float(mag[0]), ph[0]
