T363 = [1.888,1.978,2.069,2.155,2.245,2.338,2.462,2.602,2.755,2.929,3.130,3.325,3.391,3.370,3.314,3.294,3.314,3.358,3.445,3.586,3.739,3.735,3.611,3.383,3.188,3.005,2.839,2.697,2.566,2.458,2.369,2.268,2.199,2.108]
TM = [(a + b) / 2 for a, b in zip(T30, T363)]

def norm(r):
    lo, hi = min(r), max(r)
    return [(x - lo) / (hi - lo) for x in r], lo, hi

def pwl(s):
    return ", ".join(f"{v:.1f},{x:.4f}" for v, x in zip(V, s))

sNX, nlo, nhi = norm(NX[25]); sTM, tlo, thi = norm(TM)
L = []
A = L.append
A("* sw3157.lib: open behavioural models of a 3157-class SPDT analog switch used as an SPST (COM to the low-selected")
A("* throw), and of the TMUX1119 for comparison, at a 3.3 V supply.  Written for this project (whatif/sw3157); our own")
A("* work, not a vendor model and containing none.  Licence: CC BY-SA 4.0 (LICENSE beside this file), (c) the project authors.")
A("* Generated by make_lib.py (beside this file) from the digitised curves quoted there; curves.json holds them as data.")
A("*")
A("* Sources (vendor files, git-ignored, fetched and hash-checked by tools/fetch_models.py from models/manifest.json):")
A("*   74lvc1g3157/74lvc1g3157.pdf  Nexperia 74LVC1G3157 Rev. 11 (23 Aug 2023)")
A("*   ts5a3157/ts5a3157.pdf        TI TS5A3157 SCDS219D (Jul 2025)")
A("*   tmux1119/tmux1119.pdf        TI TMUX1119 SCDS401C (Feb 2024)")
A("*")
A("* Closed switch: Ron(V) = rpk - flat + flat * s(Vc), Vc = mean of the two pin voltages (the drop across the switch is")
A("* tens of mV here), s() the normalised shape (0..1 over 0-3.3 V) of a digitised typical curve:")
A(f"*   SHAPE NX : Nexperia Fig. 10 (p. 8), VCC 3.3 V, 25 C; raw {nlo:.3f}-{nhi:.3f} ohm (min at 1.6 V, max at 2.4 V),")
A("*              flatness 1.94 ohm against Table 8's typical 2.0 (ISW 24 mA, VCC 3-3.6 V).  Reading error about +/-0.05 ohm.")
A(f"*   SHAPE TM : TMUX1119 Figure 5-1 (p. 9), mean of the VDD = 3 V and 3.63 V curves; raw {tlo:.3f}-{thi:.3f} ohm.")
A("*              The table (Sec 5.6, p. 5) gives RON 3.7 typ / 8.8 max and RON_FLAT 1.9 typ at 25 C.")
A("* The TS5A3157 publishes no curve: its corners below use the NX shape *(assumption: a 3157-class shape, not TI's)*.")
A("* Vc is clamped to 0-3.3 V (the digitised span) and Ron to at least 0.1 ohm, so that Newton iterations far from the")
A("* solution never see a negative resistance.")
A("* On capacitance con is split con/2 to ground at each pin; il is a leakage current from each pin to ground.")
A("*")
A("* Corners (rpk, flat) used by whatif/sw3157 (every one quoted from the datasheet unless marked):")
A(f"*   74LVC1G3157 typ 25 C    rpk {nhi:.3f} flat {nhi-nlo:.3f}  (the digitised curve itself)")
A("*   74LVC1G3157 max         rpk 20   flat 5.04  RON(peak) max 20 ohm (Table 8, -40..85 C, VCC 3-3.6 V); RON(flat) has no")
A("*                           maximum, so the curve is scaled x 20/7.698 *(assumption: proportional scaling)*")
A("*   TS5A3157 typ 25 C       rpk 12   flat 8     (Sec 5.5 p. 6, V+ = 3 V, rON typ 12, ron(flat) typ 8)")
A("*   TS5A3157 max 25 C       rpk 20   flat 13    (rON max 20, ron(flat) max 13); Full (-40..85 C): rpk 20 flat 14")
A("*   either 3157, literal bound rpk 20 flat 0  (Ron at its 20 ohm maximum everywhere: the datasheet bound as written)")
A("*   TMUX1119 typ 25 C       rpk 3.7  flat 1.9   (Sec 5.6 p. 5);  max: rpk 8.8, flat 2.2 (the -40..125 C flatness figure)")
A("* NOT modelled: temperature (use the corners; NX tabulates its four curves in make_lib.py), Ron against current (the")
A("* tables are at 10-30 mA, this circuit carries at most about 6 mA), body diodes (add DESD at the pins where needed),")
A("* break-before-make and charge injection (TS5A3157 3 pC, Nexperia 5.0 pC at 3.3 V, TMUX1119 -6 pC).")
A("*")
for nm, s in (("NX", sNX), ("TM", sTM)):
    A(f".subckt RSWV_{nm} a b params: rpk=7.698 flat=1.941 con=18p il=0")
    A(f"Bsw a b I = V(a,b)/max({{rpk-flat}} + {{flat}}*pwl(min(max((V(a)+V(b))/2, 0), 3.3), {pwl(s)}), 0.1)")
    A("Con1 a 0 {con/2}")
    A("Con2 b 0 {con/2}")
    A("Ila a 0 {il}")
    A("Ilb b 0 {il}")
    A(".ends")
A("* open switch: coff across the open path (conservative for the +/-1.25 V pole; the datasheets give the off capacitance")
A("* of a pin to ground, not across the switch) and a leakage current from each pin")
A(".subckt RSWV_OPEN a b params: coff=6p il=0")
A("Coff a b {coff}")
A("Ila a 0 {il}")
A("Ilb b 0 {il}")
A(".ends")
