# TI TMUX1119 SCDS401C, Figure 5-1 (p. 9): VDD = 3 V (traced to 3.0 V) and VDD = 3.63 V; 0.0 V and the 3 V curve above
# 3.0 V are linear extrapolations of the neighbouring trace; the 3.3 V curve is taken as their mean *(assumption)*
