def project_symbols():
    """the two symbols KiCad's libraries lack, with the pin numbers of their datasheets"""
    # TPH2502 (3PEAK, SOP-8, datasheet "Pin Configuration (Top View)"): 1 OUTA, 2 -INA, 3 +INA, 4 V-, 5 +INB, 6 -INB, 7 OUTB,
    # 8 V+. One unit, so one symbol is one package, and a half-and-half schematic cannot lose the shared supply.
    tph = _sch.box_symbol('TPH2502', [
        ('3', '+INA', 'input', 'L', 0), ('2', '-INA', 'input', 'L', 1),
        ('5', '+INB', 'input', 'L', 3), ('6', '-INB', 'input', 'L', 4),
        ('1', 'OUTA', 'output', 'R', 0), ('7', 'OUTB', 'output', 'R', 3),
        ('8', 'V+', 'power_in', 'T', 1), ('4', 'V-', 'power_in', 'B', 1)],
        width=10.16, ref='U', fp=_design.SOP8, ds='https://www.3peakic.com/',
        desc='3PEAK TPH2502 dual 250 MHz RRIO CMOS op-amp, SOP-8 (-S suffix)')
    # ADS1115 (TI SBAS444E table 4-1, DGS/DYN): 1 ADDR, 2 ALERT/RDY, 3 GND, 4 AIN0, 5 AIN1, 6 AIN2, 7 AIN3, 8 VDD, 9 SDA, 10 SCL
    ads = _sch.box_symbol('ADS1115', [
        ('4', 'AIN0', 'input', 'L', 0), ('5', 'AIN1', 'input', 'L', 1), ('6', 'AIN2', 'input', 'L', 2),
        ('7', 'AIN3', 'input', 'L', 3), ('1', 'ADDR', 'input', 'L', 5),
        ('9', 'SDA', 'bidirectional', 'R', 0), ('10', 'SCL', 'input', 'R', 1), ('2', 'ALERT/RDY', 'output', 'R', 3),
        ('8', 'VDD', 'power_in', 'T', 1), ('3', 'GND', 'power_in', 'B', 1)],
        width=12.7, fp=_design.MSOP10, ds='https://www.ti.com/lit/ds/symlink/ads1115.pdf',
        desc='16-bit 4-input I2C ADC, VSSOP-10 DGS (SBAS444E table 4-1)')
    return [tph, ads]


def _erc_exclusions(pin_at, uid, root):
    # the LM27762's PGOOD is open drain and tied to GND as its datasheet asks when unused (SNVSAF7C table 4-1); GND carries a
    # PWR_FLAG (a power output), and an open collector on a power output is an ERC error by pin type, not by circuit. Keyed by
    # the two pins' UUIDs and the first pin's position (100 nm units), then the sheet path of the marker and of each item.
    pg = pin_at[('U401', '1')]
    return [[f"pin_to_pin|{round(pg[0] * 1e4)}|{round(pg[1] * 1e4)}|{uid('pin', 'U401', 1, '1')}|{uid('pin', '#FLG01', 1, '1')}"
             f"|/{root}|/{root}|/{root}", 'PGOOD unused, tied to GND per SNVSAF7C; GND carries the PWR_FLAG']]


def sch_cfg(**over):
    """the namespace schematic.write_all(PARTS, cfg, out_dir) takes; keyword arguments replace a field (the check's arms)"""
    cfg = types.SimpleNamespace(
        PROJECT=PROJECT, NS=NS, BLOCK_ORDER=list(BLOCK_ORDER), BLOCK_TITLE=dict(BLOCK_TITLE), PWR_FLAG_NETS=list(PWR_FLAG_NETS),
        TITLE=TITLE + ': AFE shield for the Arduino Due', REV=REV, COMMENTS=list(SCH_COMMENTS), PROJECT_SYMBOLS=project_symbols(),
        ERC_EXCLUSIONS=_erc_exclusions, SYMBOL_DIR=SYMBOL_DIR, PROPS=PROPS, FLAG_BLOCK=FLAG_BLOCK, CHECK_NC=True,
        LIB_GENERATOR='afe_v2_build_sch', FP_LIB_TABLE=FP_LIB_TABLE)
    for k, v in over.items():
        setattr(cfg, k, v)
    return cfg
