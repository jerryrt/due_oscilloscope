def _load_design(path=None):
    """import design.py under the private name pcbtools._live_v2.design; `path` is for a test that holds another copy"""
    path = path or os.path.join(PROJECT_DIR, 'design.py')
    keep = sys.dont_write_bytecode
    sys.dont_write_bytecode = True               # reading a source must not leave __pycache__ in it
    try:
        spec = importlib.util.spec_from_file_location('pcbtools._live_v2.design', path)
        m = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(m)
    finally:
        sys.dont_write_bytecode = keep
    return m


