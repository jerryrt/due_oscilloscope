"""The build inputs of the v1 board, from the frozen fixture: the ONE place that turns the old design.py / layout.py /
build_sch.py / build_pcb.py constants into the cfg objects schematic.write_all() and build.build_board() take. The tests that
compare with the old builders and the bench steps both use it, so they cannot drift apart.

    work = prepare(dir)                 copy the fixture to dir/old (the old modules are loaded from a copy, never in place)
    sch_inputs(work)  -> (parts, cfg)               for schematic.write_all(parts, cfg, out_dir)
    pcb_inputs(work, footprint_dir) -> dict(parts, cfg, place, anchors)    for build.build_board(parts, cfg, place, nets, out,
                                                                               legalise_overlaps=True, anchors=anchors)
"""
import importlib.util
import os
import shutil
import sys
import types

from .. import schematic as sch
from . import v1 as _v1

SYMDIR = os.environ.get('KICAD_SYMBOL_DIR', '/usr/share/kicad/symbols')
FPDIR = os.environ.get('KICAD_FOOTPRINT_DIR', '/usr/share/kicad/footprints')


def prepare(dir_):
    old = os.path.join(str(dir_), 'old')
    shutil.copytree(_v1.SOURCE_DIR, old)
    return old


def _load(name, path):
    keep = sys.dont_write_bytecode
    sys.dont_write_bytecode = True
    try:
        spec = importlib.util.spec_from_file_location(name, path)
        m = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(m)
    finally:
        sys.dont_write_bytecode = keep
    return m


def _modules(old, names):
    """load the old scripts of the copy in `old` under namespaced names. The old build scripts import their siblings by plain
    name (design, sexpr, layout): `old` is on sys.path only while they load (the path is restored whole, the scripts add entries of their own), and every plain-named module they brought in
    is removed from sys.modules again, so a later `import sexpr` in this process cannot find this board's copy."""
    before, path = set(sys.modules), list(sys.path)
    sys.path.insert(0, old)
    try:
        return [_load(f'pcbtools._fixture_v1_build.{os.path.basename(old)}.{n}', os.path.join(old, n + '.py')) for n in names]
    finally:
        sys.path[:] = path                       # the old scripts also insert their own folder at import
        for k in set(sys.modules) - before:
            f = getattr(sys.modules[k], '__file__', None) or ''
            if '.' not in k and os.path.abspath(f).startswith(os.path.abspath(old) + os.sep):
                del sys.modules[k]


def _exclusions(pin_at, uid, root):
    pg = pin_at[('U401', '1')]
    return [[f"pin_to_pin|{round(pg[0] * 1e4)}|{round(pg[1] * 1e4)}|{uid('pin', 'U401', 1, '1')}|{uid('pin', '#FLG01', 1, '1')}"
             f"|/{root}|/{root}|/{root}", 'PGOOD unused, tied to GND per SNVSAF7C; GND carries the PWR_FLAG']]


def sch_inputs(old):
    design, oldsch = _modules(old, ['design', 'build_sch'])
    tmux = sch.box_symbol('TMUX1119', [
        ('4', 'S1', 'passive', 'L', 0), ('6', 'S2', 'passive', 'L', 2), ('1', 'SEL', 'input', 'L', 4),
        ('5', 'D', 'passive', 'R', 1), ('2', 'VDD', 'power_in', 'T', 1), ('3', 'GND', 'power_in', 'B', 1)],
        width=10.16, fp=design.SC706, ds='https://www.ti.com/lit/ds/symlink/tmux1119.pdf',
        desc='SPDT 5 V analog switch, SC70-6 (SCDS401C table 4-1): SEL low = S1-D')
    cfg = types.SimpleNamespace(
        PROJECT='afe-proto', NS=str(oldsch.NS), BLOCK_ORDER=oldsch.ORDER, BLOCK_TITLE=oldsch.BLOCK_TITLE,
        PWR_FLAG_NETS=oldsch.PWR_FLAG_NETS, TITLE='AFE full range design 01: AFE shield for the Arduino Due', REV='FR-01',
        COMMENTS=['Generated by hardware/afe-proto/kicad/build_sch.py from design.py: edit those, not this file',
                  'Values and parts: whatif/bom.txt. Connectivity: the simulated circuit (docs/architecture.md)',
                  'Own work, CC BY-SA 4.0'],
        PROJECT_SYMBOLS=[tmux], ERC_EXCLUSIONS=_exclusions, SYMBOL_DIR=SYMDIR)
    return design.PARTS, cfg


def pcb_inputs(old, footprint_dir=None):
    design, layout, oldsch, oldpcb = _modules(old, ['design', 'layout', 'build_sch', 'build_pcb'])
    place = {ref: (x, y, rot) for ref, (x, y, rot) in layout.PLACE.items()}
    for ref, (x, y, d) in oldpcb.HEADERS.items():
        place[ref] = (x, y, oldpcb.ROT[d], True)
    place['J607'] = (oldpcb.XIO[0] + 2.54, oldpcb.XIO[1], 0, True)
    for ref, y in oldpcb.BNCS.items():
        place[ref] = (oldpcb.BNC_X, y, -90)
    place['MH601'] = (*oldpcb.MH, 0, True)
    place['MH602'] = (*oldpcb.MH602, 0, True)
    cfg = types.SimpleNamespace(
        PROJECT='afe-proto', NS=str(oldsch.NS), OUTLINE=(17.0, 0.0, 117.0, 53.34),
        REFERENCE_OUTLINE=[(1, 0), (98.06, 0), (99.06, 1), (99.06, 2.54), (101.6, 5.08), (101.6, 37.846), (99.06, 40.386),
                           (99.06, 51.816), (97.536, 53.34), (1, 53.34), (0, 52.34), (0, 1), (1, 0)],
        TITLE='AFE full range design 01: AFE shield for the Arduino Due, placement', REV='FR-01',
        COMMENTS=['Generated by hardware/afe-proto/kicad/build_pcb.py from design.py; not routed', 'Own work, CC BY-SA 4.0'],
        FOOTPRINT_DIR=footprint_dir or FPDIR, PROJECT_LIB_DIR=os.path.join(old, 'lib', 'afe.pretty'),
        MODEL_OVERRIDE=oldpcb.MODEL_OVERRIDE, MODELS_DIR=os.path.join(old, '3d'))
    anchors = set(oldpcb.HEADERS) | set(oldpcb.BNCS) | {'J607', 'MH601', 'MH602'}
    return dict(parts=design.PARTS, cfg=cfg, place=place, anchors=anchors, design=design)
